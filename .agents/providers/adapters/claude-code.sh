#!/bin/bash
# Claude Code has no per-provider concept -- it only speaks the Anthropic Messages API,
# selected globally via ANTHROPIC_BASE_URL/ANTHROPIC_AUTH_TOKEN. Writing those into
# ~/.claude/settings.json (as originally planned) would silently redirect EVERY Claude
# Code session on this machine to the local GLM proxy, including this one -- too
# invasive for what should be an opt-in provider. Instead this adapter generates a
# `claude-<provider-id>` launcher in ~/.local/bin that sets the env vars only for that
# invocation and execs the real `claude` binary, mirroring Codex's opt-in `--profile`
# model.
#
# The token clients present to the local proxy is the proxy's own locally-generated
# master key (~/.dtx-providers/proxy.env), never the upstream provider's real
# API key -- the proxy holds that server-side.

set -euo pipefail
cd -- "$(dirname -- "${BASH_SOURCE[0]}")"
source lib.sh

action="${1:-}"
provider_id="${2:-}"
[[ -n $action && -n $provider_id ]] || dtx_fail "usage: claude-code.sh <apply|remove> <provider-id>"
command -v jq >/dev/null || dtx_fail "jq is required"

provider=$(dtx_provider_json "$provider_id")
launcher="$HOME/.local/bin/claude-$provider_id"

case "$action" in
apply)
  ../proxy/ensure-proxy.sh

  model_id=$(jq -r '.models[0].id' <<<"$provider")
  model_name="$provider_id/$model_id"

  mkdir -p "$(dirname "$launcher")"
  cat >"$launcher" <<EOF
#!/bin/bash
# Generated by dtx-providers-tui -- do not edit by hand. Regenerate via:
#   dtx-providers-tui apply claude-code $provider_id
set -a
source "\$HOME/.dtx-providers/proxy.env"
set +a
export ANTHROPIC_BASE_URL="http://127.0.0.1:4444"
export ANTHROPIC_AUTH_TOKEN="\$DTX_PROXY_MASTER_KEY"
export ANTHROPIC_MODEL="$model_name"
exec claude "\$@"
EOF
  chmod +x "$launcher"
  echo "claude-code: wrote $launcher (run 'claude-$provider_id' instead of 'claude' to use $provider_id)"
  ;;
remove)
  rm -f "$launcher"
  echo "claude-code: removed $launcher"
  ;;
*)
  dtx_fail "unknown action: $action"
  ;;
esac
